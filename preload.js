const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  load: () => ipcRenderer.invoke('data:load'),
  save: (data) => ipcRenderer.invoke('data:save', data),
  openExternal: (url, chromeProfile) => ipcRenderer.invoke('open:external', url, chromeProfile),
  chromeProfiles: () => ipcRenderer.invoke('chrome:profiles'),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  exportData: (data) => ipcRenderer.invoke('data:export', data),
  importData: () => ipcRenderer.invoke('data:import'),
  captureSite: (id, url) => ipcRenderer.invoke('sites:capture', { id, url }),
  fetchSheet: (url, key) => ipcRenderer.invoke('sheet:fetch', { url, key }),
  listApps: () => ipcRenderer.invoke('apps:list'),
  appIcon: (appPath) => ipcRenderer.invoke('apps:icon', appPath),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  onUpdate: (cb) => ipcRenderer.on('update:available', (_e, update) => cb(update)),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateProgress: (cb) => ipcRenderer.on('update:progress', (_e, progress) => cb(progress)),
  setAppearance: (appearance) => ipcRenderer.invoke('appearance:set', appearance),
  setIcon: (dataUrl) => ipcRenderer.invoke('icon:set', dataUrl),
  asanaGet: () => ipcRenderer.invoke('asana:get'),
  asanaSync: () => ipcRenderer.invoke('asana:sync'),
  asanaSeen: () => ipcRenderer.invoke('asana:seen'),
  asanaConnect: (token) => ipcRenderer.invoke('asana:connect', token),
  asanaUsers: (projectGid) => ipcRenderer.invoke('asana:users', projectGid),
  asanaCreateTask: (task) => ipcRenderer.invoke('asana:create-task', task),
  onAsana: (cb) => ipcRenderer.on('asana:update', (_e, s) => cb(s)),
  cloudGet: () => ipcRenderer.invoke('cloud:get'),
  cloudSync: () => ipcRenderer.invoke('cloud:sync'),
  cloudRedeem: (code) => ipcRenderer.invoke('cloud:redeem', code),
  cloudMyCode: () => ipcRenderer.invoke('cloud:my-code'),
  cloudLogout: () => ipcRenderer.invoke('cloud:logout'),
  cloudUsers: () => ipcRenderer.invoke('cloud:users'),
  cloudInvite: (email, name, role) => ipcRenderer.invoke('cloud:invite', email, name, role),
  cloudUserCode: (email) => ipcRenderer.invoke('cloud:user-code', email),
  cloudSetRole: (email, role) => ipcRenderer.invoke('cloud:set-role', email, role),
  cloudRemoveUser: (email) => ipcRenderer.invoke('cloud:remove-user', email),
  cloudTeam: () => ipcRenderer.invoke('cloud:team'),
  cloudSaveNote: (note) => ipcRenderer.invoke('cloud:save-note', note),
  cloudDeleteNote: (owner, id) => ipcRenderer.invoke('cloud:delete-note', owner, id),
  cloudNotesSeen: () => ipcRenderer.invoke('cloud:notes-seen'),
  onOpenNotes: (cb) => ipcRenderer.on('cloud:open-notes', () => cb()),
  cloudPublishTools: (tools) => ipcRenderer.invoke('cloud:publish-tools', tools),
  onCloud: (cb) => ipcRenderer.on('cloud:update', (_e, s) => cb(s)),
  onDataRemote: (cb) => ipcRenderer.on('data:remote', (_e, d) => cb(d)),
});
